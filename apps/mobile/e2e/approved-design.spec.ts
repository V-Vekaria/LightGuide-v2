import {test,expect} from '@playwright/test';
test('first use, four-stage capture, shoot dates and complete backup round trip',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');
 await page.getByRole('button',{name:'Start my first setup',exact:true}).click();
 await page.getByRole('button',{name:'Continue to setup',exact:true}).click();
 await page.getByLabel('Setup name',{exact:true}).fill('Approved workspace');
 await page.getByRole('button',{name:'Next: Photos',exact:true}).click();
 await expect(page.getByRole('button',{name:'Add result photo',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Next: Lights',exact:true}).click();
 await page.getByRole('button',{name:'Add manual measurements',exact:true}).click();
 await page.getByLabel('Light height above floor (cm)',{exact:true}).fill('170');
 await page.getByRole('button',{name:'Next: Camera',exact:true}).click();
 await page.getByLabel('ISO',{exact:true}).fill('100');
 await page.getByRole('button',{name:'Save setup',exact:true}).click();
 await expect(page.getByText('Approved workspace',{exact:true})).toBeVisible();
 await page.goto('/shoot');
 await page.getByLabel('Shoot name',{exact:true}).fill('Future portrait');
 await page.getByLabel('Shoot date (optional)',{exact:true}).fill('20-09-2026');
 await expect(page.getByRole('button',{name:'Save shoot',exact:true})).toBeDisabled();
 await expect(page.getByText(/Choose today or a future date/)).toBeVisible();
 await page.getByLabel('Shoot date (optional)',{exact:true}).fill('01-01-2030');
 await page.getByRole('button',{name:'Save shoot',exact:true}).click();
 await expect(page.getByText('Future portrait',{exact:true})).toBeVisible();
 await page.goto('/backup');
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export backup',exact:true}).click();
 const path=await (await download).path();
 await page.goto('/equipment');
 await page.getByLabel('Equipment name',{exact:true}).fill('After backup');
 await page.getByRole('button',{name:'Save equipment',exact:true}).click();
 await page.goto('/backup');
 const chooser=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Choose backup file',exact:true}).click();
 await (await chooser).setFiles(path!);
 await expect(page.getByText('Replace this workspace?',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Confirm',exact:true}).click();
 await expect(page.getByText('Approved workspace',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Equipment tab',exact:true}).click();
 await expect(page.getByText('After backup',{exact:true})).toHaveCount(0);
 await page.screenshot({path:'artifacts/approved-design-equipment.png'});
});
