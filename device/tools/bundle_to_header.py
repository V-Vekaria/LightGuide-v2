"""Embed the built app bundle into the firmware as a C header.

Why embedded rather than uploaded to the filesystem:

* No `mklittlefs` step. The ESP32 core does not ship a filesystem image tool,
  so an uploaded bundle would need one sourced separately and kept in step.
* **The app and firmware cannot drift apart.** They ship as one product, and a
  board serving a bundle from a different build than its own firmware is
  exactly the mismatch the single-repo decision was meant to prevent. Embedding
  makes it impossible rather than merely unlikely.

Everything is gzipped at build time and served with `Content-Encoding: gzip`,
which every browser that can run the app already understands.

    npm run build                                   # from the repo root
    python device/tools/bundle_to_header.py

Writes device/firmware/05_integration/www_bundle.h
"""

import gzip
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
DIST = REPO / "dist"
OUT = REPO / "device" / "firmware" / "05_integration" / "www_bundle.h"

MIME = {
    ".html": "text/html",
    ".js": "application/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".json": "application/json",
    ".png": "image/png",
    ".woff2": "font/woff2",
}


def c_name(rel: str) -> str:
    return "f_" + "".join(ch if ch.isalnum() else "_" for ch in rel)


def main() -> int:
    if not DIST.is_dir():
        print(f"no dist/ at {DIST} - run `npm run build` first", file=sys.stderr)
        return 1

    files = sorted(p for p in DIST.rglob("*") if p.is_file())
    if not files:
        print("dist/ is empty", file=sys.stderr)
        return 1

    chunks, table, raw_total, gz_total = [], [], 0, 0

    for path in files:
        rel = "/" + path.relative_to(DIST).as_posix()
        raw = path.read_bytes()
        # mtime=0 so rebuilding identical input produces an identical header,
        # which keeps the firmware binary reproducible.
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        raw_total += len(raw)
        gz_total += len(gz)

        name = c_name(rel)
        body = ",".join(str(b) for b in gz)
        chunks.append(
            f"static const uint8_t {name}[] PROGMEM = {{{body}}};"
        )
        mime = MIME.get(path.suffix.lower(), "application/octet-stream")
        table.append(f'  {{"{rel}", "{mime}", {name}, sizeof({name})}},')
        print(f"  {rel:<34} {len(raw):>7} -> {len(gz):>6} gz  ({mime})")

    OUT.write_text(
        "// Generated by device/tools/bundle_to_header.py - do not edit.\n"
        "// Regenerate after every `npm run build`.\n"
        f"// {len(files)} files, {raw_total} bytes raw, {gz_total} bytes gzipped.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        + "\n".join(chunks)
        + "\n\nstruct WwwFile {\n"
        "  const char *path;\n"
        "  const char *mime;\n"
        "  const uint8_t *data;\n"
        "  size_t len;\n"
        "};\n\n"
        "static const WwwFile WWW_FILES[] = {\n"
        + "\n".join(table)
        + "\n};\n"
        f"static const size_t WWW_FILE_COUNT = {len(files)};\n",
        encoding="utf-8",
    )

    print(f"\n{OUT.relative_to(REPO)}")
    print(f"{len(files)} files, {raw_total} raw -> {gz_total} gzipped "
          f"({100 * gz_total // max(raw_total, 1)}%)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
